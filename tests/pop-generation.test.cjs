  await ctx.popGenerateLyrics();assert.equal(nodes['pop-sect-ta'].value,previous);
  let resolve;
  ctx.callOpenAI=()=>new Promise(r=>resolve=r);
  const pending=ctx.popAiWriteStyle(run('VTS.pop'),run('popWriteToken'));
