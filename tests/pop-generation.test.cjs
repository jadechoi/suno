  const previous=nodes['pop-sect-ta'].value;
  ctx.popEditLyrics('[Bridge]\nWrong section');
  assert.equal(nodes['pop-sect-ta'].value,previous);
  assert.match(nodes['pop-ai-status'].textContent,/미반영/);
  run("VTS.pop.userLyrics='';");
